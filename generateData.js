function randomName() {
  const first = firstNames[Math.floor(Math.random() * firstNames.length)];
  const last = lastNames[Math.floor(Math.random() * lastNames.length)];
  return `${first} ${last}`;
}

function randomUsername(i) {
  return `user_${i}_${Math.floor(Math.random() * 99999)}`;
}

function randomPhone() {
  const prefix = ["05", "06", "07"][Math.floor(Math.random() * 3)];
  let number = "";
  for (let i = 0; i < 8; i++) {
    number += Math.floor(Math.random() * 10);
  }
  return prefix + number;
}

const total = 200000; // 🔥 change to 100 first for testing
const outputPath = path.join(__dirname, 'data.json');

const stream = fs.createWriteStream(outputPath, { encoding: 'utf8' });

stream.write('[\n');

for (let i = 0; i < total; i++) {
  const record = {
    fullName: randomName(),
    username: randomUsername(i),
    phoneNumber: randomPhone()
  };

  stream.write(JSON.stringify(record)); // ✅ no heavy formatting

  if (i < total - 1) {
    stream.write(',\n');
  }
}

stream.write('\n]');
stream.end();

stream.on('finish', () => {
  console.log(`✅ Generated ${total} records in: ${outputPath}`);
});

stream.on('error', (err) => {
  console.error('❌ Stream error:', err);
});